import { test, expect, type Page } from '@playwright/test';
import { writeFileSync } from 'fs';
import {
  installApiGuard,
  mockSharedBatchUploadUrls,
  mockSharedMomentConfirm,
  mockSharedUploadStatus,
} from './helpers/mocks';
import { installStorageClearScript } from './helpers/storage';
import { MOMENT_EVENT_IDENTIFIER } from './fixtures/api-data';

/**
 * EV-48 in a real browser: 10 real JPEG photos of ~6 MB go through the actual
 * client optimizer (createImageBitmap + canvas.toBlob). The page records, on
 * one clock (performance.now), the click on "Compartir momento", every
 * optimization and every S3 PUT.
 *
 * Baseline: before EV-48 the engine optimized every image one by one and only
 * then presigned and PUT anything, so its first PUT could not happen before the
 * last optimization ended. The same run measures that floor and the actual
 * first PUT.
 */

const PAGE_URL = `/events/upload?e=${MOMENT_EVENT_IDENTIFIER}`;
const PHOTO_COUNT = 10;
const MIN_PHOTO_BYTES = 5 * 1024 * 1024;
const MAX_PHOTO_BYTES = 7 * 1024 * 1024;

interface PipelineProbe {
  active: number;
  peak: number;
  decodeStarts: number[];
  encodeEnds: number[];
  puts: number[];
  click: number | null;
}

/** Real, decodable JPEGs of ~6 MB, generated by the browser's own encoder. */
async function generatePhotos(page: Page): Promise<Buffer[]> {
  const photos: Buffer[] = [];
  for (let index = 0; index < PHOTO_COUNT; index += 1) {
    const base64 = await page.evaluate(
      async ({ seed, min, max }) => {
        const canvas = document.createElement('canvas');
        canvas.width = 4000;
        canvas.height = 3000;
        const context = canvas.getContext('2d')!;
        const image = context.createImageData(canvas.width, canvas.height);
        let state = seed * 2654435761;
        const random = () => {
          state = (state * 1103515245 + 12345) & 0x7fffffff;
          return state & 0xff;
        };
        // 2x2 blocks of noise over a gradient: photo-like entropy.
        for (let y = 0; y < canvas.height; y += 2) {
          for (let x = 0; x < canvas.width; x += 2) {
            const r = (x / 16 + random() / 2) & 0xff;
            const g = (y / 12 + random() / 2) & 0xff;
            const b = random();
            for (const [dx, dy] of [[0, 0], [1, 0], [0, 1], [1, 1]]) {
              const offset = ((y + dy) * canvas.width + (x + dx)) * 4;
              image.data[offset] = r;
              image.data[offset + 1] = g;
              image.data[offset + 2] = b;
              image.data[offset + 3] = 255;
            }
          }
        }
        context.putImageData(image, 0, 0);
        const encode = (quality: number) =>
          new Promise<Blob>((resolve) =>
            canvas.toBlob((blob) => resolve(blob!), 'image/jpeg', quality),
          );
        // Binary-search the quality that lands the file at ~6 MB.
        let low = 0.05;
        let high = 1;
        let best = await encode(0.9);
        for (let step = 0; step < 8; step += 1) {
          if (best.size >= min && best.size <= max) break;
          const quality = (low + high) / 2;
          best = await encode(quality);
          if (best.size > max) high = quality;
          else low = quality;
        }
        const bytes = new Uint8Array(await best.arrayBuffer());
        let binary = '';
        for (let i = 0; i < bytes.length; i += 0x8000) {
          binary += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
        }
        return btoa(binary);
      },
      { seed: index + 1, min: MIN_PHOTO_BYTES, max: MAX_PHOTO_BYTES },
    );
    photos.push(Buffer.from(base64, 'base64'));
  }
  return photos;
}

/** Records optimizations and PUTs on the page clock. */
function installPipelineProbe() {
  const probe: PipelineProbe = {
    active: 0,
    peak: 0,
    decodeStarts: [],
    encodeEnds: [],
    puts: [],
    click: null,
  };
  (window as unknown as { __ev48: PipelineProbe }).__ev48 = probe;

  // On this page only the image optimizer (momentUploadImage.ts) calls
  // createImageBitmap/toBlob for JPEGs: an optimization runs from the decode
  // to the toBlob callback. A failed decode falls back to new Image() and
  // still ends in toBlob, so it is not counted as finished there. The rare
  // "no 2d context" early return would leave the counter high, which can only
  // make the peak assertion stricter.
  const originalCreateImageBitmap = window.createImageBitmap.bind(window);
  window.createImageBitmap = ((...args: Parameters<typeof createImageBitmap>) => {
    probe.active += 1;
    probe.peak = Math.max(probe.peak, probe.active);
    probe.decodeStarts.push(performance.now());
    return originalCreateImageBitmap(...args);
  }) as typeof createImageBitmap;
  const originalToBlob = HTMLCanvasElement.prototype.toBlob;
  HTMLCanvasElement.prototype.toBlob = function (callback, ...rest) {
    return originalToBlob.call(
      this,
      (blob) => {
        probe.active = Math.max(0, probe.active - 1);
        probe.encodeEnds.push(performance.now());
        callback(blob);
      },
      ...rest,
    );
  };

  const originalOpen = XMLHttpRequest.prototype.open;
  const originalSend = XMLHttpRequest.prototype.send;
  const methods = new WeakMap<XMLHttpRequest, string>();
  XMLHttpRequest.prototype.open = function (
    this: XMLHttpRequest,
    method: string,
    ...rest: unknown[]
  ) {
    methods.set(this, method.toUpperCase());
    return (originalOpen as (...args: unknown[]) => void).call(this, method, ...rest);
  } as typeof XMLHttpRequest.prototype.open;
  XMLHttpRequest.prototype.send = function (this: XMLHttpRequest, body) {
    if (methods.get(this) === 'PUT') probe.puts.push(performance.now());
    return originalSend.call(this, body);
  };

  document.addEventListener(
    'click',
    (event) => {
      const button = (event.target as Element | null)?.closest('button');
      // "Compartir momento" for one file, "Compartir 10 momentos" for ten.
      if (probe.click === null && /^Compartir/.test(button?.textContent?.trim() ?? '')) {
        probe.click = performance.now();
      }
    },
    true,
  );
}

let photos: Buffer[] = [];

test.beforeAll(async ({ browser }) => {
  const generator = await browser.newPage();
  try {
    photos = await generatePhotos(generator);
  } finally {
    await generator.close();
  }
});

test.beforeEach(async ({ page }) => {
  await installStorageClearScript(page);
  await installApiGuard(page);
});

test('10 photos of ~6 MB: first PUT before the last optimization, at most 2 at once', async ({ page }, testInfo) => {
  test.setTimeout(180_000);
  for (const photo of photos) {
    expect(photo.length).toBeGreaterThanOrEqual(MIN_PHOTO_BYTES);
    expect(photo.length).toBeLessThanOrEqual(MAX_PHOTO_BYTES);
  }
  const paths = photos.map((photo, index) => {
    const path = testInfo.outputPath(`foto-${index + 1}.jpg`);
    writeFileSync(path, photo);
    return path;
  });

  let presigns = 0;
  let confirms = 0;
  await page.addInitScript(installPipelineProbe);
  await mockSharedUploadStatus(page, MOMENT_EVENT_IDENTIFIER, { uploadsRemaining: 30 });
  await mockSharedBatchUploadUrls(page, MOMENT_EVENT_IDENTIFIER, {
    uploadsRemaining: 30,
    onBatch: () => {
      presigns += 1;
    },
  });
  await mockSharedMomentConfirm(page, MOMENT_EVENT_IDENTIFIER, {
    uploadsRemaining: 20,
    onConfirm: () => {
      confirms += 1;
    },
  });

  await page.goto(PAGE_URL);
  await expect(page.getByRole('heading', { name: /Comparte tus momentos/ })).toBeVisible({ timeout: 15_000 });
  await page.locator('input[type="file"]').first().setInputFiles(paths);
  const share = page.getByRole('button', { name: `Compartir ${PHOTO_COUNT} momentos` });
  await expect(share).toBeEnabled({ timeout: 30_000 });
  await share.click();

  await expect.poll(() => confirms, { timeout: 150_000 }).toBe(PHOTO_COUNT);
  const probe = await page.evaluate(
    () => (window as unknown as { __ev48: PipelineProbe }).__ev48,
  );

  expect(probe.click).not.toBeNull();
  const click = probe.click!;
  const firstPutMs = Math.min(...probe.puts) - click;
  const lastOptimizationEndMs = Math.max(...probe.encodeEnds) - click;
  const firstOptimizationEndMs = Math.min(...probe.encodeEnds) - click;
  const result = {
    photos: photos.map((photo) => photo.length),
    optimizations: probe.decodeStarts.length,
    peakConcurrentOptimizations: probe.peak,
    puts: probe.puts.length,
    presignRequests: presigns,
    confirms,
    firstOptimizationEndMs: Math.round(firstOptimizationEndMs),
    firstPutMs: Math.round(firstPutMs),
    // Conservative floor for the pre-EV-48 engine: measured here with 2
    // optimizations at once, while the old engine ran them one by one and then
    // made a batch presign, so its real first PUT came later than this.
    baselineFloorMs: Math.round(lastOptimizationEndMs),
    savedVsFloorMs: Math.round(lastOptimizationEndMs - firstPutMs),
  };
  await testInfo.attach('ev48-first-put.json', {
    body: JSON.stringify(result, null, 2),
    contentType: 'application/json',
  });
  console.log(`[EV-48] ${testInfo.project.name} ${JSON.stringify(result)}`);

  // Every photo went through the real optimizer, never more than 2 at once.
  expect(probe.decodeStarts).toHaveLength(PHOTO_COUNT);
  expect(probe.peak).toBeLessThanOrEqual(2);
  // One presign per file (EV-48), then one PUT and one confirm each.
  expect(presigns).toBe(PHOTO_COUNT);
  expect(probe.puts).toHaveLength(PHOTO_COUNT);
  // The first PUT does not wait for the other optimizations: it starts before
  // the last one ends, which is the earliest the pre-EV-48 engine could PUT.
  expect(firstPutMs).toBeLessThan(lastOptimizationEndMs);
});
